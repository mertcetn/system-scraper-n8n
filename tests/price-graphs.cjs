const assert = require('node:assert/strict');
const {addGraphObservation, readGraphHistory, graphSeries, priceChartConfig, graphLocalDay} = require('../lib/price-graphs');
const product = {current_price: 100, in_stock: true};
let raw = addGraphObservation(null, product, '2026-10-20T08:00:00.000Z');
raw = addGraphObservation(raw, {...product,current_price:90}, '2026-10-20T09:00:00.000Z');
raw = addGraphObservation(raw, {...product,current_price:95}, '2026-10-20T10:00:00.000Z');
let h = readGraphHistory(raw);
assert.equal(h.daily.length,1); assert.equal(h.daily[0].price,90); assert.equal(h.daily[0].observed_at,'2026-10-20T09:00:00.000Z');
raw = addGraphObservation(raw, {...product,current_price:90}, '2026-10-21T09:00:00.000Z');
raw = addGraphObservation(raw, {...product,current_price:80}, '2026-10-22T09:00:00.000Z');
h = readGraphHistory(raw); assert.equal(h.weekly.length,1); assert.equal(h.weekly[0].price,80); assert.equal(h.monthly[0].price,80);
assert.equal(graphSeries(raw,'month','2026-10-23T09:00:00Z').minimum.observed_at,'2026-10-22T09:00:00.000Z');
raw = addGraphObservation(raw, {...product,current_price:1,in_stock:false}, '2026-10-23T09:00:00.000Z');
assert.equal(readGraphHistory(raw).monthly[0].price,80);
raw = addGraphObservation(raw, {...product,current_price:70}, '2026-11-01T09:00:00.000Z');
h = readGraphHistory(raw); assert.equal(h.daily.length,1); assert.equal(h.monthly.length,2); assert.equal(h.monthly[0].price,80);
assert.equal(graphSeries(raw,'week','2026-11-01T09:00:00Z').values.filter(v=>v!==null).length,1);
assert.equal(graphSeries(raw,'year','2026-11-01T09:00:00Z').labels.length,12);
assert.equal(graphSeries(raw,'max','2026-11-01T09:00:00Z').minimum.price,70);
assert(priceChartConfig(raw,'max','2026-11-01T09:00:00Z').options.plugins.subtitle.text.includes('2026-11-01'));
assert.equal(graphLocalDay('2026-10-31T21:01:00Z'),'2026-11-01');
const tied = addGraphObservation(raw, {...product,current_price:70}, '2026-11-02T09:00:00.000Z');
assert.equal(readGraphHistory(tied).monthly[1].observed_at,'2026-11-01T09:00:00.000Z');
const reset = readGraphHistory(addGraphObservation(raw, product, '2026-11-02T09:00:00.000Z',true));
assert.equal(reset.monthly.length,1); assert.equal(reset.monthly[0].price,100);
assert.equal(reset.archived[0].monthly.length,2);
assert.throws(()=>readGraphHistory('{broken'));
assert.throws(()=>graphSeries(raw,'invalid','2026-11-01T09:00:00Z'));
const invalid = addGraphObservation(null,{...product,current_price:NaN},'2026-11-01T09:00:00Z');
assert.equal(readGraphHistory(invalid).daily.length,0);
let long = null;
for(let year=2020;year<=2026;year++) for(let month=1;month<=12;month++) long=addGraphObservation(long,product,year+'-'+String(month).padStart(2,'0')+'-15T12:00:00.000Z');
assert.equal(readGraphHistory(long).monthly.length,84);
assert.equal(graphSeries(long,'year','2026-12-20T12:00:00Z').values.length,12);
console.log('PASS: daily/weekly/monthly minima, observation dates and ties, stock guard, rolling retention, unlimited monthly history, gaps, Istanbul dates, identity reset, malformed data');
